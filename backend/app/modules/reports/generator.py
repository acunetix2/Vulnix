"""Report generation (JSON and Markdown).

Untrusted scanner text is escaped or fenced so a hostile filename or message
cannot inject active content into the rendered report.
"""

import json
from datetime import UTC, datetime

from app.db.models import Finding, Scan, ToolRun


def _md_escape(value: str | None) -> str:
    if not value:
        return ""
    return str(value).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ").replace("\r", " ")


def _fence(value: str | None, limit: int = 1500) -> str:
    # Neutralize fence-breaking sequences before wrapping in a code block.
    text = (value or "")[:limit].replace("```", "'''")
    return f"```\n{text}\n```"


def build_json_report(scan: Scan, tool_runs: list[ToolRun], findings: list[Finding]) -> dict:
    return {
        "report_version": "1.0",
        "generated_at": datetime.now(UTC).isoformat(),
        "scan": {
            "id": scan.id,
            "status": scan.status,
            "created_at": scan.created_at.isoformat() if scan.created_at else None,
            "started_at": scan.started_at.isoformat() if scan.started_at else None,
            "completed_at": scan.completed_at.isoformat() if scan.completed_at else None,
            "options": scan.options,
            "summary": scan.summary,
        },
        "tool_runs": [
            {
                "tool": r.tool_name,
                "version": r.tool_version,
                "status": r.status,
                "exit_code": r.exit_code,
                "duration_ms": r.duration_ms,
                "finding_count": r.finding_count,
            }
            for r in tool_runs
        ],
        "findings": [
            {
                "id": f.id,
                "rule_id": f.rule_id,
                "title": f.title,
                "category": f.category,
                "severity": f.severity,
                "confidence": f.confidence,
                "file_path": f.file_path,
                "start_line": f.start_line,
                "end_line": f.end_line,
                "evidence": f.evidence,
                "scanner_message": f.scanner_message,
                "remediation": f.remediation,
                "status": f.status,
                "triage_note": f.triage_note,
            }
            for f in findings
        ],
        "limitations": (
            "Findings come from deterministic scanners. "
            "Absence of findings is not proof of security."
        ),
    }


def build_markdown_report(scan: Scan, tool_runs: list[ToolRun], findings: list[Finding]) -> str:
    lines = [
        "# Vulnix Scan Report",
        "",
        f"- Scan ID: `{scan.id}`",
        f"- Status: {_md_escape(scan.status)}",
        f"- Created: {scan.created_at.isoformat() if scan.created_at else 'n/a'}",
        f"- Completed: {scan.completed_at.isoformat() if scan.completed_at else 'n/a'}",
        "",
        "## Tools",
        "",
        "| Tool | Version | Status | Duration (ms) | Findings |",
        "|---|---|---|---|---|",
    ]
    for r in tool_runs:
        lines.append(
            f"| {_md_escape(r.tool_name)} | {_md_escape(r.tool_version)} | {_md_escape(r.status)} "
            f"| {r.duration_ms if r.duration_ms is not None else ''} | {r.finding_count} |"
        )
    summary = scan.summary or {}
    by_sev = summary.get("by_severity", {})
    lines += [
        "",
        "## Summary",
        "",
        f"Total findings: {summary.get('total_findings', len(findings))}",
        "",
        "| Severity | Count |",
        "|---|---|",
    ]
    for sev in ("critical", "high", "medium", "low", "info"):
        lines.append(f"| {sev} | {by_sev.get(sev, 0)} |")
    lines += ["", "## Findings", ""]
    if not findings:
        lines.append("No findings recorded.")
    for f in findings:
        location = f"{f.file_path or 'unknown'}" + (
            f":{f.start_line}-{f.end_line}" if f.start_line else ""
        )
        lines += [
            f"### {_md_escape(f.title)}",
            "",
            f"- Severity: **{_md_escape(f.severity)}** | Confidence: {_md_escape(f.confidence)} "
            f"| Category: {_md_escape(f.category)}",
            f"- Rule: {_md_escape(f.rule_id)} | Status: {_md_escape(f.status)}",
            f"- Location: `{_md_escape(location)}`",
            "",
            "**Evidence**",
            "",
            _fence(f.evidence or f.scanner_message or "No evidence recorded."),
            "",
            f"**Remediation:** {_md_escape(f.remediation) or 'See rule documentation.'}",
            "",
        ]
    lines += [
        "---",
        "",
        "_Generated by Vulnix. Findings are scanner-produced evidence; "
        "absence of findings does not guarantee the code is secure._",
        "",
    ]
    return "\n".join(lines)


def build_csv_report(scan: Scan, tool_runs: list[ToolRun], findings: list[Finding]) -> str:
    import csv
    import io

    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow([
        "Finding ID",
        "Severity",
        "Category",
        "Title",
        "Rule ID",
        "File Path",
        "Start Line",
        "End Line",
        "Status",
        "Scanner Message",
        "Remediation",
    ])
    for f in findings:
        writer.writerow([
            f.id,
            f.severity,
            f.category,
            f.title,
            f.rule_id,
            f.file_path or "",
            f.start_line or "",
            f.end_line or "",
            f.status,
            f.scanner_message or f.evidence or "",
            f.remediation or "",
        ])
    return output.getvalue()


def serialize_json(data: dict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=True, default=str)
